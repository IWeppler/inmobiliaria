CREATE OR REPLACE FUNCTION "public"."update_all_normalized_prices"("new_rate" numeric) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  -- Primero, actualiza las propiedades en ARS (precio 1 a 1)
  UPDATE public.properties
  SET price_normalized_ars = price
  WHERE currency = 'ARS';

  -- Segundo, actualiza las propiedades en USD (precio * nueva tasa)
  UPDATE public.properties
  SET price_normalized_ars = price * new_rate
  WHERE currency = 'USD';
END;
$$;


